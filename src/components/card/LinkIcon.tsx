export const ICON_LABELS: Record<string, string> = Object.fromEntries(
  LINK_PLATFORMS.map((p) => [p.id, p.label]),
);

export function LinkIcon({ icon, className }: { icon: string; className?: string }) {
  const I = (MAP as Record<string, LucideIcon>)[icon] ?? LinkIcon2;
  return <I className={className} aria-hidden />;
}
